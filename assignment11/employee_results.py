import sqlite3
import pandas as pd
import matplotlib.pyplot as plt

# 1. Connect to the SQLite database
conn = sqlite3.connect('../db/lesson.db')

# 2. The provided SQL query to fetch employee revenue
query = """
SELECT 
    last_name, 
    SUM(price * quantity) AS revenue 
FROM employees e 
JOIN orders o ON e.employee_id = o.employee_id 
JOIN line_items l ON o.order_id = l.order_id 
JOIN products p ON l.product_id = p.product_id 
GROUP BY e.employee_id;
"""

# 3. Load the query results directly into a Pandas DataFrame
employee_results = pd.read_sql_query(query, conn)

# Close the database connection
conn.close()

# 4. Use Pandas plotting functionality to create a bar chart
# We set last_name on the x-axis and revenue on the y-axis
ax = employee_results.plot(
    kind='bar', 
    x='last_name', 
    y='revenue', 
    legend=False, 
    color='skyblue', 
    edgecolor='black'
)

# 5. Give appropriate titles and labels
plt.title('Total Revenue Generated by Employee Last Name', fontsize=14, fontweight='bold', pad=15)
plt.xlabel('Employee Last Name', fontsize=12, labelpad=10)
plt.ylabel('Total Revenue ($)', fontsize=12, labelpad=10)

# Optional: Rotate x-axis names so they are easy to read
plt.xticks(rotation=45)

# Tight layout automatically adjusts subplot params so everything fits comfortably
plt.tight_layout()

# 6. Show the plot
plt.show()